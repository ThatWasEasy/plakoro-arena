#!/usr/bin/env python3
"""Turn the 秘笈手冊 Google Doc into structured content the app can render and sell.

Two sources, because neither is sufficient alone:

  * the published doc (`/pub`) holds the text, and re-publishing keeps it in sync, so prose
    edits never need a manual re-export;
  * the local Google Docs export holds the images as real files. The published copy hotlinks
    `docs.google.com/docs-images-rt/...`, which is a public URL that also expires — exactly
    the two properties paid artwork must not have.

Output goes to `handbook-build/`, which is gitignored on purpose. This repo is public and its
build is served as static files; a handbook committed here is a handbook given away. Paid
content reaches players through the API's player_unlocks check and nowhere else.

    python3 scripts/build-handbook.py --export "temp/Plakoro 秘笈手冊"

Add `--url <published url>` to pull fresh text, or omit it to use the export's own HTML.
"""
import argparse
import json
import pathlib
import re
import shutil
import sys
import unicodedata
import urllib.request
from html.parser import HTMLParser

# `kind` on a sellable unit. Mirrors the shop's product kinds so one can be mapped to the
# other without a translation table.
BASE, CHARACTER, SPECIAL = 'base', 'character', 'special'

# Chapter three is the product: 84% of the book, and the half that splits per character.
CH3_PREFIX = '三、'

# "啟程套組" / "探險盒 01" sit at the same heading level as the characters under them, so the
# grouping is positional rather than structural — a set header owns every character section
# after it until the next set header.
SET_HEADER = re.compile(r'^(啟程套組|探險盒\s*\d+|.*套組)\s*$')

# "7. 甲賀忍蛙(EBC02-001)" — the code in the brackets is what ties a section to a card, and
# the only part worth trusting. The leading number restarts inside each set, so it is a label,
# not an id.
CHARACTER_HEADING = re.compile(r'^\s*(\d+)\.\s*(.+?)\s*[（(]\s*([A-Za-z]{3}\d{2}(?:-\d{3})?)\s*[)）]\s*$')

# A template left in the document for the authors to copy. Not a product.
TEMPLATE_HEADING = re.compile(r'^\s*X\.\s')

# h5 is not a heading. The authors used it as a styling shortcut for three unrelated things,
# so 1,759 of them would otherwise flood the table of contents and turn star ratings into
# chapter titles. Each is recognised by shape, which is reliable because the shapes are
# generated by the authors' own template rather than typed freehand.
RATING = re.compile(r'[★☆]{3,}')
PERCENT_TRIPLE = re.compile(r'^\s*[\d.]+%\s*/\s*[\d.]+%\s*/\s*[\d.]+%\s*$')
HIT_VALUE = re.compile(r'^\s*(打擊|傷害)\s*\d+\s*$')
SPEAKER = re.compile(r'^\s*(Andy|Shawn)\s*[：:]')

BLOCK_TAGS = {'p', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'li', 'td', 'th', 'tr', 'table'}


class DocParser(HTMLParser):
    """Flattens the export into an ordered block list, dropping Google's styling entirely.

    The class soup (`c11 c39`) carries no meaning worth keeping — the semantic skeleton is in
    the tag names, and that survived the export intact.
    """

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks = []
        self.in_body = False
        self.skip_depth = 0
        self.tag_stack = []
        self.text = []
        self.table = None
        self.row = None
        # Google wraps every cell's text in its own <p>, so a cell is a little document rather
        # than a string. Collecting into this while it is open is what keeps that text in the
        # table instead of leaking out as 71 tables' worth of loose paragraphs.
        self.cell = None
        self.img_index = 0

    # -- helpers ---------------------------------------------------------------
    def _flush(self):
        raw = ''.join(self.text)
        self.text = []
        return re.sub(r'[ \t ]+', ' ', raw).strip()

    def _current(self):
        return self.tag_stack[-1] if self.tag_stack else None

    # -- parser hooks ----------------------------------------------------------
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == 'body':
            self.in_body = True
            return
        if not self.in_body:
            return
        if tag in ('style', 'script'):
            self.skip_depth += 1
            return
        if tag == 'img':
            # Position, not filename: the published copy names images by expiring CDN URL and
            # the export names them `imageN.png`, but both emit them in the same document
            # order, so the Nth reference is the same picture in either source.
            self.blocks.append({'type': 'img', 'index': self.img_index})
            self.img_index += 1
            return
        if tag == 'table':
            self.table = []
            return
        if tag == 'tr' and self.table is not None:
            self.row = []
            return
        if tag in ('td', 'th') and self.row is not None:
            self.cell = []
        if tag in BLOCK_TAGS:
            self.text = []
            self.tag_stack.append(tag)

    def handle_endtag(self, tag):
        if tag == 'body':
            self.in_body = False
            return
        if not self.in_body:
            return
        if tag in ('style', 'script'):
            self.skip_depth = max(0, self.skip_depth - 1)
            return
        if tag == 'table' and self.table is not None:
            if any(any(c for c in r) for r in self.table):
                self.blocks.append({'type': 'table', 'rows': self.table})
            self.table = None
            return
        if tag == 'tr' and self.table is not None:
            if self.row:
                self.table.append(self.row)
            self.row = None
            return
        if tag not in BLOCK_TAGS or self._current() != tag:
            return
        self.tag_stack.pop()
        text = self._flush()
        if tag in ('td', 'th'):
            if self.row is not None:
                if text:
                    self.cell.append(text)
                self.row.append('\n'.join(self.cell or []))
            self.cell = None
            return
        if not text:
            return
        # Inside a cell everything is cell text, whatever tag the authors reached for.
        if self.cell is not None:
            self.cell.append(text)
            return
        if tag in ('h1', 'h2', 'h3', 'h4'):
            self.blocks.append({'type': 'heading', 'level': int(tag[1]), 'text': text})
        elif tag == 'h5' or tag == 'h6':
            self.blocks.append(classify_h5(text))
        else:
            self.blocks.append({'type': 'p', 'text': text})

    def handle_data(self, data):
        if self.in_body and not self.skip_depth:
            self.text.append(data)


def classify_h5(text):
    """Decide what an h5 actually is.

    The authors reached for h5 whenever they wanted a particular look, so the same tag carries
    a reviewer's aside, a star rating and a bare damage figure. Keeping them as headings would
    be wrong in the table of contents and wrong on the page; once separated, the ratings and
    figures can be rendered as what they are.
    """
    m = RATING.search(text)
    if m:
        # The whole review lives in the same h5 as the stars: "Shawn：★★☆☆☆；打擊回復招。…".
        # Split them, so the stars can be drawn as stars and the prose read as prose — left
        # whole, a 358-character paragraph would be rendered as if it were a score.
        speaker = SPEAKER.match(text)
        stars = m.group(0)
        comment = text[m.end():].lstrip('；;：: ').strip()
        # Most ratings carry only punctuation after the stars — the review itself is written in
        # the paragraph below. Keeping "。" would render as a one-character review.
        if not re.search(r'[\w\u4e00-\u9fff]', comment):
            comment = ''
        return {
            'type': 'rating',
            'by': speaker.group(1) if speaker else None,
            'filled': stars.count('★'),
            'outOf': len(stars),
            'comment': comment,
        }
    if PERCENT_TRIPLE.match(text):
        return {'type': 'stat', 'kind': 'odds', 'values': [v.strip() for v in text.split('/')]}
    if HIT_VALUE.match(text):
        return {'type': 'stat', 'kind': 'damage', 'text': text}
    speaker = SPEAKER.match(text)
    if speaker:
        return {'type': 'aside', 'by': speaker.group(1),
                'text': text[speaker.end():].lstrip('：: ').strip()}
    return {'type': 'aside', 'by': None, 'text': text}


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'plakoro-handbook-build'})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode('utf-8', errors='replace')


def split_units(blocks, report):
    """Group the flat block list into the things that can be sold separately.

    Everything outside chapter three is one `base` unit for now; chapter three becomes one unit
    per character. A set header ("探險盒 01") is recorded as the group a character belongs to
    rather than as a unit of its own — bundles are assembled in the shop, not baked in here, so
    that regrouping a set later is a pricing change and not a rebuild.
    """
    units = []
    base = {'id': 'base', 'kind': BASE, 'title': '本體', 'group': None, 'blocks': []}
    units.append(base)

    cur, in_ch3, group = base, False, None
    for b in blocks:
        if b['type'] == 'heading' and b['level'] == 1:
            in_ch3 = b['text'].startswith(CH3_PREFIX)
            group = None
            if not in_ch3:
                cur = base
            cur['blocks'].append(b)
            continue

        if in_ch3 and b['type'] == 'heading' and b['level'] == 2:
            title = b['text']
            if TEMPLATE_HEADING.match(title):
                report.append(('skipped', f'略過樣板區塊「{title}」'))
                cur = {'id': '_template', 'kind': SPECIAL, 'title': title, 'group': None,
                       'blocks': [], 'drop': True}
                continue
            m = CHARACTER_HEADING.match(title)
            if m:
                _, name, code = m.groups()
                code = code.upper()
                cur = {'id': f'chara.{code}', 'kind': CHARACTER, 'title': name,
                       'cardCode': code, 'group': group, 'blocks': []}
                units.append(cur)
                continue
            if SET_HEADER.match(title):
                group = title.strip()
                report.append(('group', f'套組「{group}」'))
                cur = base
                continue
            report.append(('warn', f'第三章有個 h2 既不是角色也不是套組：「{title}」'))
        cur['blocks'].append(b)

    return [u for u in units if not u.get('drop')]


def image_refs(export_dir):
    """The ordered list of image files, one entry per reference in the document.

    Counting unique files is the wrong question: the book makes 53 references to 40 files,
    because several diagrams are reused. The export's own HTML is the only place that records
    which reference points at which file, so that list is read rather than reconstructed — an
    earlier version matched them by ordinal and silently put the wrong diagram under a third
    of the paragraphs.
    """
    html_path = next(pathlib.Path(export_dir).glob('*.html'), None)
    if not html_path:
        return []
    raw = html_path.read_text(encoding='utf-8', errors='replace')
    return [r.split('/')[-1] for r in re.findall(r'<img[^>]+src="([^"]+)"', raw)]


def copy_images(export_dir, out_dir, refs, used, report):
    """Copies every referenced file once, under a name that does not depend on Google's."""
    src = pathlib.Path(export_dir) / 'images'
    if len(refs) != used:
        report.append(('error',
                       f'圖片引用數對不上：文字來源 {used} 次，匯出版 {len(refs)} 次 —— '
                       '兩邊不是同一版文件，請重新匯出'))
    dest = out_dir / 'images'
    dest.mkdir(parents=True, exist_ok=True)
    missing = []
    for name in set(refs):
        f = src / name
        if f.exists():
            shutil.copy2(f, dest / name)
        else:
            missing.append(name)
    if missing:
        report.append(('error', f'匯出資料夾缺少 {len(missing)} 個檔案：{sorted(missing)[:5]}'))
    return refs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--export', required=True, help='Google Docs 匯出資料夾（圖片來源）')
    ap.add_argument('--url', help='已發布的文件網址（文字來源；省略則用匯出的 HTML）')
    ap.add_argument('--out', default='handbook-build')
    args = ap.parse_args()

    export_dir = pathlib.Path(args.export)
    if not export_dir.is_dir():
        sys.exit(f'找不到匯出資料夾：{export_dir}')

    if args.url:
        html = fetch(args.url)
        source = args.url
    else:
        local = next(export_dir.glob('*.html'), None)
        if not local:
            sys.exit(f'{export_dir} 裡沒有 .html')
        html = local.read_text(encoding='utf-8', errors='replace')
        source = str(local)

    parser = DocParser()
    parser.feed(html)
    report = []
    units = split_units(parser.blocks, report)

    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    refs = image_refs(export_dir)
    images = copy_images(export_dir, out, refs, parser.img_index, report)
    for u in units:
        for b in u['blocks']:
            if b['type'] == 'img' and b['index'] < len(images):
                b['src'] = images[b['index']]

    def block_text(b):
        """Every piece of prose in a block, wherever the authors put it.

        Counting only `text` undercounts wildly: most of this book is written inside table
        cells, so a character section that reads as 1,200 words reported as 63.
        """
        parts = [b.get('text', ''), b.get('comment', '')]
        for row in b.get('rows', []):
            parts.extend(row)
        return ''.join(parts)

    def wc(u):
        return sum(len(re.sub(r'\s+', '', block_text(b))) for b in u['blocks'])

    doc = {
        'source': source,
        'units': [{**u, 'words': wc(u), 'images': sum(1 for b in u['blocks'] if b['type'] == 'img')}
                  for u in units],
    }
    # NFC, because macOS hands back decomposed filenames and a browser asks for composed ones —
    # the same mismatch that 404'd the character art.
    path = out / 'handbook.json'
    path.write_text(unicodedata.normalize('NFC', json.dumps(doc, ensure_ascii=False, indent=2)),
                    encoding='utf-8')

    # The proof reader ships beside the data so there is never a build without a way to read it.
    reader = pathlib.Path(__file__).with_name('handbook-reader.html')
    if reader.exists():
        shutil.copy2(reader, out / 'reader.html')

    print(f'來源：{source}')
    print(f'輸出：{path}  （{len(units)} 個可販售單位，'
          f'{len(set(images))} 張圖／{len(images)} 次引用）\n')
    print(f"{'unit id':22}{'類型':<10}{'字數':>8}{'圖':>4}  標題")
    for u in doc['units']:
        print(f"  {u['id']:20}{u['kind']:<10}{u['words']:>8,}{u['images']:>4}  {u['title']}"
              + (f"  [{u['group']}]" if u.get('group') else ''))
    print(f'\n閱讀器：cd {out} && python3 -m http.server 4800   → http://localhost:4800/reader.html')
    # Sections the authors have probably not finished. Worth saying out loud, because each one
    # is something that would otherwise be sold as if it were complete.
    chars = [u for u in doc['units'] if u['kind'] == CHARACTER]
    if chars:
        typical = sorted(u['words'] for u in chars)[len(chars) // 2]
        for u in chars:
            if u['words'] < typical * 0.6:
                report.append(('warn', f"「{u['title']}」只有 {u['words']:,} 字，"
                                       f'約是其他角色（{typical:,}）的一半 —— 可能還沒寫完'))
            if u['images'] == 0:
                report.append(('warn', f"「{u['title']}」沒有任何圖"))

    total = sum(u['words'] for u in doc['units'])
    print(f'\n合計 {total:,} 字')
    if report:
        print('\n--- 需要你確認 ---')
        for level, msg in report:
            print(f'  {{"error":"❌","warn":"⚠️ ","group":"  ","skipped":"  "}}'
                  .format() if False else f'  {"❌" if level=="error" else "⚠️ " if level=="warn" else "·"} {msg}')


if __name__ == '__main__':
    main()
